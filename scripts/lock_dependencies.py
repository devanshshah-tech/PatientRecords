"""Freeze only this app's dependency closure from a reviewed installed environment."""
from importlib.metadata import distribution
from pathlib import Path
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

root = Path(__file__).resolve().parent.parent
pending = [Requirement(line.strip()) for line in
    (root / 'requirements.txt').read_text(encoding='utf-8-sig').splitlines()
    if line.strip() and not line.startswith('#')]
seen = set()
locked = {}
while pending:
    requirement = pending.pop()
    key = (canonicalize_name(requirement.name), tuple(sorted(requirement.extras)))
    if key in seen:
        continue
    seen.add(key)
    installed = distribution(requirement.name)
    if installed.version not in requirement.specifier:
        raise RuntimeError(f'Installed {requirement.name} does not meet its requirement.')
    locked[canonicalize_name(installed.metadata['Name'])] = installed.version
    for raw in installed.requires or []:
        dependency = Requirement(raw)
        if not dependency.marker or any(dependency.marker.evaluate({'extra': extra})
            for extra in {'', *requirement.extras}):
            pending.append(dependency)
lines = ['# Reviewed application dependency closure; generated by scripts/lock_dependencies.py.',
    '# Includes Windows tzdata; also installable on Linux.']
lines.extend(f'{name}=={version}' for name, version in sorted(locked.items()))
(root / 'requirements.lock').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'Locked {len(locked)} application packages.')
